"""Generate Listi's original two-panel folder emblem as SVG and native HVIF.

Small polygon-only HVIF writer for this artwork, not a general SVG converter.
Format reference: Haiku r1beta6 src/libs/icon/flat_icon/FlatIconFormat.h.
No Haiku icon artwork or implementation is copied.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
# Painter order, original integer coordinates on Haiku's 64-unit icon grid.
SHAPES = [
    ("26374455", [(10, 49), (52, 42), (61, 50), (18, 61), (7, 56)]),
    ("283b49", [(7, 13), (24, 9), (32, 16), (54, 12), (59, 50), (17, 59), (6, 51)]),
    ("d99e35", [(9, 15), (23, 12), (31, 19), (52, 15), (56, 48), (18, 56), (9, 49)]),
    ("ffe49a", [(9, 15), (23, 12), (27, 16), (11, 20)]),
    ("a56b29", [(9, 24), (18, 29), (20, 55), (9, 49)]),
    ("283b49", [(11, 23), (52, 15), (56, 47), (17, 55)]),
    ("fff6d6", [(13, 25), (30, 22), (34, 49), (19, 52)]),
    ("d9edf0", [(33, 21), (50, 18), (53, 45), (37, 48)]),
    ("ffffff", [(13, 25), (30, 22), (30, 25), (14, 28)]),
    ("ffffff", [(33, 21), (50, 18), (50, 21), (34, 24)]),
    ("e3a53a", [(14, 29), (30, 26), (31, 31), (15, 34)]),
    ("3e899d", [(34, 25), (50, 22), (51, 27), (35, 30)]),
    ("947443", [(17, 37), (29, 35), (29, 37), (17, 39)]),
    ("947443", [(18, 42), (30, 40), (30, 42), (18, 44)]),
    ("947443", [(19, 47), (27, 45), (27, 47), (19, 49)]),
    ("538396", [(37, 33), (49, 31), (49, 33), (37, 35)]),
    ("538396", [(38, 38), (50, 36), (50, 38), (38, 40)]),
    ("538396", [(39, 43), (47, 41), (47, 43), (39, 45)]),
    ("ffe49a", [(17, 55), (56, 47), (56, 50), (18, 58)]),
]


def generate():
    colors = list(dict.fromkeys(color for color, _ in SHAPES))
    data = bytearray(b"ncif")
    data.append(len(colors))
    for color in colors:
        raw = bytes.fromhex(color)
        data.append(1 if len(raw) == 4 else 3)  # RGBA / opaque RGB
        data.extend(raw)
    data.append(len(SHAPES))
    for _, points in SHAPES:
        data.extend((10, len(points)))  # closed polygon, no curves
        for point in points:
            for coordinate in point:
                assert -32 <= coordinate <= 95
                data.append(coordinate + 32)
    data.append(len(SHAPES))
    for index, (color, _) in enumerate(SHAPES):
        data.extend((10, colors.index(color), 1, index, 0))
    (ROOT / "Listi.hvif").write_bytes(data)
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">',
           '<title>Listi: two-panel file manager</title>']
    for color, points in SHAPES:
        opacity = f' fill-opacity="{int(color[6:],16)/255:.6f}"' if len(color) == 8 else ''
        vertices = ' '.join(f'{x},{y}' for x, y in points)
        svg.append(f'<polygon fill="#{color[:6]}"{opacity} points="{vertices}"/>')
    (ROOT / "Listi.svg").write_text('\n'.join(svg + ['</svg>', '']))
    lines = ['// Generated by artwork/generate_icon.py. Original artwork, MIT.',
             'resource vector_icon {']
    for offset in range(0, len(data), 32):
        lines.append('    $"' + data[offset:offset+32].hex().upper() + '"')
    (ROOT.parent / 'src' / 'ListiIcon.rdef').write_text('\n'.join(lines + ['};', '']))
    print(f'Generated {len(data)}-byte native Listi icon')


if __name__ == '__main__':
    generate()
